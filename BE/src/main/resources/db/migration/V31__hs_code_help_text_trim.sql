-- HS 코드 입력칸 아래 설명 문구 삭제 (2026-08-23 강 요청)
--
-- V30에서 HS 코드를 자유 입력으로 바꾸면서 help_text에 자릿수 체계 설명(류/호/소호)을
-- 세 문장 붙였다. 그런데 입력 화면에서 이 문구가 입력칸 바로 아래에 통째로 깔리면서,
-- 다른 항목보다 칸 하나가 두 배로 길어지고 폼 전체가 설명문으로 밀렸다. 정작 입력하는
-- 사람에게 필요한 건 "몇 자리로 어떻게 쓰는가" 하나뿐이고, 그건 예시값 한 줄이면 된다.
--
-- 자릿수 강제는 그대로 validation_rule이 한다(V30) - 설명을 지운다고 검증이 느슨해지지
-- 않는다. 짧아진 help_text는 FE에서 placeholder로만 쓰이고 입력칸 아래에는 아무것도
-- 그리지 않는다(makerVals.js hint 규칙 참고).
-- =====================================================================

UPDATE requirement_field
   SET help_text = '예: 720851'
 WHERE field_code = 'HS_CODE';
