-- =====================================================================
-- DPP에 사용자가 붙이는 이름 - 2026-08-20 강 요청
--   "DPP 생성 시 각 DPP에 대한 이름을 사용자가 지정할 수 있게. 이건 시스템 내에서만
--    활용되고 DPP 레지스트리에서는 기본키로 조회"
--
-- 지금까지 제조사 화면은 DPP를 product_model.internal_sku(또는 'DPP-'+dpp_id)로만
-- 불렀다. 같은 모델로 여러 DPP를 만들면 목록에서 서로 구분이 안 된다.
--
-- 이 이름은 순수하게 내부 식별 편의용이다:
--   - 공개 여권(/p/{public_uuid})과 EU 레지스트리 조회는 지금처럼 public_uuid /
--     model_name / internal_sku만 쓴다. display_name은 내보내지 않는다.
--   - 규제상 의미가 없으므로 requirement_field에도 넣지 않는다(완성도 계산과 무관).
--   - 유일성 제약도 두지 않는다. 사용자가 같은 이름을 여러 개 붙이는 걸 막을 이유가 없다.
-- =====================================================================

ALTER TABLE dpp ADD COLUMN display_name VARCHAR(120);

COMMENT ON COLUMN dpp.display_name IS
    '사용자가 붙인 DPP 이름(내부 식별용). 공개 여권·레지스트리에는 노출하지 않는다';
