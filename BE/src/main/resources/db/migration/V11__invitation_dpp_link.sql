-- "협력사 초대" 화면 재설계: 이제 초대는 "회사 대 회사" 일반 연결이 아니라 특정 DPP에
-- 문서/필드를 제출해줄 협력사를 그 DPP에 지정해서 보내는 것 - 하나의 DPP에 여러 협력사가
-- (원자재공급사·물류사 등 역할별로) 동시에 붙을 수 있다.
--
-- invitation.dpp_id는 nullable로 둔다 - 과거에 만들어진(DPP 미지정) 초대 행과의 호환,
-- 그리고 나중에 다시 "회사 단위 일반 연결" 초대가 필요해질 가능성을 열어둔다.
-- =====================================================================

ALTER TABLE invitation ADD COLUMN dpp_id BIGINT REFERENCES dpp(dpp_id);
