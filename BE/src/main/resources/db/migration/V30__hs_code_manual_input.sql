-- =====================================================================
-- HS 코드를 드롭다운 선택이 아니라 직접 입력으로 (2026-08-23 강 요청)
--
-- 그동안 requirement_field.HS_CODE는 data_type='CODE' + code_group='HS_CODE'였다.
-- 그래서 화면에 code_master의 HS_CODE 목록(V3__seed_master.sql, '7208 열간압연 평판압연
-- 제품' ~ '7216 형강' 8개)이 셀렉트로 떴다. 두 가지가 잘못이다.
--   1) 그 8개는 우리가 데모용으로 골라 넣은 4자리 류/호일 뿐이고, 실제 HS 코드 체계
--      전체가 아니다. 목록에 없는 품목은 아예 입력할 수 없다.
--   2) HS는 기본 6자리(류 2 + 호 2 + 소호 2)가 국제 표준인데 4자리만 고를 수 있어서,
--      애초에 규격에 맞는 값을 넣을 수가 없었다.
-- 자유 입력으로 바꾸고, 자릿수 규칙을 validation_rule로 강제한다.
--
-- code_master의 HS_CODE 코드들은 지우지 않는다 - 세관 화면 등 다른 곳에서 라벨 조회에
-- 쓸 수 있고, 지워서 얻을 이득이 없다. 이 필드가 참조만 안 하면 된다.
-- =====================================================================

UPDATE requirement_field
   SET data_type      = 'STRING',
       code_group     = NULL,
       -- 6자리(국제 공통) / 8자리 / 10자리(국내 HSK)까지 허용. 그 외 자릿수는 거부한다.
       validation_rule = '^[0-9]{6}([0-9]{2}([0-9]{2})?)?$',
       help_text      = '예: 720851 · 기본 6자리는 전 세계 공통으로 사용하는 국제 기준입니다. '
                        || '앞 2자리는 류(상품군), 다음 2자리는 호(종류·가공도), '
                        || '그 다음 2자리는 소호(세분류)를 나타냅니다.'
 WHERE field_code = 'HS_CODE';
